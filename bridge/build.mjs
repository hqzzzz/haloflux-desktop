/**
 * Assemble src/live.js + src/bridge.js into the single `client.js` artifact,
 * mirroring how dsh-haloflux builds its client bundle.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const order = ['live.js', 'bridge.js'];

const fragments = order.map((file) => {
  const abs = path.join(root, 'src', file);
  if (!fs.existsSync(abs)) throw new Error(`missing fragment: src/${file}`);
  const code = fs.readFileSync(abs, 'utf8').trimEnd();
  return `    /* ================= src/${file} ================= */\n${code}\n`;
});

const out = `// GENERATED by build.mjs - do not edit. dsh-haloflux-bridge.
window.__ModuleLoader__.load({
  id: 'dsh-haloflux-bridge',
  factory(require) {
    const React = require('react');
${fragments.join('\n')}
    return HalofluxBridge;
  },
});
`;

const dest = path.join(root, 'client.js');
fs.writeFileSync(dest, out);
console.log(`client.js written: ${(out.length / 1024).toFixed(1)} KB`);
